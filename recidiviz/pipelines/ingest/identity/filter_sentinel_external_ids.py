"""PTransform that strips sentinel external IDs from the identity fragments
generated by a single ingest view."""
import logging
from collections.abc import Iterator

import apache_beam as beam
import attr

from recidiviz.common.constants.identity import PersonType
from recidiviz.common.constants.tenants import Tenant
from recidiviz.persistence.entity.base_entity import RootEntity
from recidiviz.persistence.entity.identity.identity_fragment_entities import (
    IdentityFragment,
)
from recidiviz.pipelines.ingest.identity.identity_ingest_pipeline_config import (
    IdentityIngestPipelineConfig,
)
from recidiviz.pipelines.ingest.types import UpperBoundDate
from recidiviz.utils.types import assert_type

# Identifies an external ID value within a single snapshot (upper-bound date) of
# a single ingest view: (upper_bound_date, external_id, id_type).
DatedExternalIdKey = tuple[UpperBoundDate, str, str]

# Coarse upper bound on how many sentinel external id keys we expect to find in a
# single view. Exceeding it more likely signals a misconfigured threshold than
# that many genuine sentinels, so we fail loudly rather than silently strip a
# huge number of external IDs.
# TODO(OBT-39311): Replace this absolute-count guard with per-view tracking of
# exactly which external IDs were stripped (written to a BQ audit table) and a
# validation on the *fraction* of a view's external IDs stripped, which is the
# signal we actually care about.
MAX_SENTINEL_EXTERNAL_IDS_PER_VIEW = 50


class FilterSentinelExternalIds(beam.PTransform):
    """PTransform that strips sentinel external IDs from the identity fragments
    generated by a single ingest view.

    A sentinel external ID is a placeholder value (e.g. InmateNum='000000')
    shared by many unrelated people. Left in place, a sentinel groups those
    unrelated people's fragments under one external ID key. Depending on the
    fragments, this either crashes the downstream per-view merge (when their
    scalar attributes conflict) or links the unrelated people so that graph
    traversal later collapses them into one giant cluster.

    An external ID value is a sentinel if the number of fragments carrying it
    exceeds the per-tenant, per-person-type maximum from
    `IdentityIngestPipelineTenantConfig.get_max_ids_for_type` for its id_type.
    Fragments are counted per (upper_bound_date, external_id, id_type)—the same
    granularity `MergeIngestViewRootEntityTrees` groups by—so a legitimate ID
    recurring across snapshot dates (the same person present in every snapshot)
    is not miscounted as a sentinel.

    This count-based test assumes identity ingest views produce one row per
    person: multi-valued demographics (aliases, races, phone numbers, ...) must
    be aggregated into arrays within a single row, not expanded across rows.
    Under that assumption a real external ID lands on exactly one fragment, so
    any value on more than the configured maximum number of fragments is a
    genuine sentinel. A view that instead emits one row per alias (or other
    child record) would repeat a real person's ID across fragments and cause it
    to be stripped, silently dropping that person. Identity views MUST
    therefore aggregate rather than expand (see the aggregate-vs-expand
    requirement on the per-state identity-view work, TODO(OBT-38477)).

    The threshold is deliberately strict. At this stage we would rather
    over-exclude than admit a sentinel that creates a false cluster requiring
    a manual split, since the goal is stable identities.
    """

    def __init__(
        self,
        *,
        # Name of the ingest view whose fragments are being filtered (used in
        # log and error messages).
        ingest_view_name: str,
        # The tenant this pipeline is running for.
        tenant: Tenant,
        # The single person type every fragment from this view carries (read
        # from the view's manifest). Selects which per-person-type config
        # supplies the sentinel thresholds.
        person_type: PersonType,
        # Config providing the per-tenant, per-person-type sentinel thresholds.
        pipeline_config: IdentityIngestPipelineConfig,
    ) -> None:
        super().__init__()
        self.ingest_view_name = ingest_view_name
        self.tenant = tenant
        self.person_type = person_type
        self.pipeline_config = pipeline_config

    def expand(
        self,
        # Elements are typed as RootEntity to match the declared output type of
        # the upstream GenerateEntities transform (Beam checks the transforms'
        # declared types for consistency), but at runtime every entity is an
        # IdentityFragment.
        input_or_inputs: beam.PCollection[tuple[UpperBoundDate, RootEntity]],
    ) -> beam.PCollection[tuple[UpperBoundDate, RootEntity]]:
        """Strips the fragments in the given collection of any external sentinel
        IDs, and returns those with any external IDs remaining.
        """

        sentinel_keys = (
            input_or_inputs
            | f"Extract dated external id keys for {self.ingest_view_name}"
            >> beam.FlatMap(self._to_dated_external_id_keys)
            | f"Count {self.ingest_view_name} fragments per external id key"
            >> beam.combiners.Count.PerElement()
            | f"Identify {self.ingest_view_name} sentinel external ids"
            >> beam.FlatMap(self._to_sentinel_key_if_above_max)
        )
        _ = (
            sentinel_keys
            | f"Count {self.ingest_view_name} sentinel external ids"
            >> beam.combiners.Count.Globally()
            | f"Assert {self.ingest_view_name} sentinel count within limit"
            >> beam.Map(self._assert_sentinel_count_within_limit)
        )
        return (
            input_or_inputs
            | f"Strip sentinel external ids from {self.ingest_view_name} fragments"
            >> beam.FlatMap(
                self._strip_sentinel_external_ids,
                sentinel_keys=beam.pvalue.AsList(sentinel_keys),
            )
        )

    @staticmethod
    def _to_dated_external_id_keys(
        element: tuple[UpperBoundDate, RootEntity],
    ) -> Iterator[DatedExternalIdKey]:
        """Yields one (upper_bound_date, external_id, id_type) key per external
        ID on the fragment."""
        upper_bound_date, entity = element
        fragment = assert_type(entity, IdentityFragment)
        for external_id in fragment.external_ids:
            yield (upper_bound_date, external_id.external_id, external_id.id_type)

    def _to_sentinel_key_if_above_max(
        self,
        element: tuple[DatedExternalIdKey, int],
    ) -> Iterator[DatedExternalIdKey]:
        """For a single (upper_bound_date, external_id, id_type) key and the
        number of fragments carrying it, yields the key if that count exceeds
        the configured maximum for the id_type (i.e. the external ID value is a
        sentinel), and logs the exclusion. Yields nothing for non-sentinel
        external IDs."""
        key, fragment_count = element
        upper_bound_date, external_id, id_type = key

        tenant_config = self.pipeline_config.get_tenant_clustering_config(
            self.tenant, self.person_type
        )
        max_ids = tenant_config.get_max_ids_for_type(id_type)
        if fragment_count <= max_ids:
            return

        logging.warning(
            "Excluding sentinel external id (external_id=[%s], id_type=[%s], "
            "fragment_count=[%s]) found in view [%s] at upper bound date [%s]: "
            "fragment count exceeds the maximum of [%s] for this id type.",
            external_id,
            id_type,
            fragment_count,
            self.ingest_view_name,
            upper_bound_date,
            max_ids,
        )
        yield key

    def _assert_sentinel_count_within_limit(self, sentinel_count: int) -> None:
        """Fails the pipeline if the number of sentinel external id keys found
        for this view exceeds MAX_SENTINEL_EXTERNAL_IDS_PER_VIEW, which more
        likely signals a misconfigured threshold than that many genuine
        sentinels."""
        if sentinel_count > MAX_SENTINEL_EXTERNAL_IDS_PER_VIEW:
            raise ValueError(
                f"Found [{sentinel_count}] sentinel external id keys in view "
                f"[{self.ingest_view_name}] for tenant [{self.tenant}], which "
                f"exceeds the maximum of [{MAX_SENTINEL_EXTERNAL_IDS_PER_VIEW}]. "
                f"This likely indicates a misconfigured sentinel threshold."
            )

    @staticmethod
    def _strip_sentinel_external_ids(
        element: tuple[UpperBoundDate, RootEntity],
        sentinel_keys: list[DatedExternalIdKey],
    ) -> Iterator[tuple[UpperBoundDate, RootEntity]]:
        """Yields the given fragment with any sentinel external IDs removed,
        or nothing if all the fragment's external IDs are sentinels."""
        upper_bound_date, entity = element
        fragment = assert_type(entity, IdentityFragment)
        kept_external_ids = [
            external_id
            for external_id in fragment.external_ids
            if (upper_bound_date, external_id.external_id, external_id.id_type)
            not in sentinel_keys
        ]
        # Sentinels should be rare, so most fragments should have none stripped.
        # Re-yield the original element to avoid a per-fragment attr.evolve on
        # this common no-op path.
        if len(kept_external_ids) == len(fragment.external_ids):
            yield element
            return
        if not kept_external_ids:
            return
        yield upper_bound_date, attr.evolve(fragment, external_ids=kept_external_ids)
