"""Utilities for parsing the Google Docs that hold PG ticket PII.

Two doc shapes are supported:

1. **Per-ticket docs** (current). Every ticket filed now gets its own private
   Google Doc, created automatically and linked from a banner at the top of the
   ticket body. `extract_pii_doc_id` pulls the doc ID out of a ticket body, and
   `parse_doc` turns the doc into text; the agent reads the whole thing and
   locates the client IDs itself.

   Deliberately, nothing here knows the doc's template — not its section
   headings, not its placeholder prompts. That template is generated by an
   automation outside this repo, so any code that matched on it would break
   silently and permissively when a heading was reworded. Whether a run actually
   got usable PII is enforced downstream instead, by refusing to post a
   diagnosis unless the run resolved a person_id (see main() in
   run_pg_ticket_diagnosis.py).

2. **The shared go/github-pii doc** (legacy, for tickets filed before the
   per-ticket cutover). One doc for every ticket, where each ticket's section is
   delimited by a header line that begins with a ticket identifier: a GitHub
   issue number ("#12345", hash required) or a Linear ID ("OBT-36184", hash
   optional). A header may list more than one — e.g. "#OBT-36212 and #88494".
   `find_issue_section` extracts the section for a given identifier.
   TODO(OBT-44025): drop shape 2 and everything supporting it once every ticket
   we might still diagnose has its own PII doc.
"""
import re

# Stands in for a pasted image, which text extraction can't read. Kept in the
# output so the agent can see that a doc holds screenshots and say so.
IMAGE_PLACEHOLDER = "[IMAGE]"

# The banner the per-ticket doc automation prepends to the ticket body links the
# doc like `[Open PII doc](<https://docs.google.com/document/d/<ID>/edit>)`. The
# ID character class stops at the "/" before "edit" and at the closing ">".
_PII_DOC_LINK_RE = re.compile(r"docs\.google\.com/document/d/([A-Za-z0-9_-]+)")

# TODO(OBT-44025): delete this regex and _ticket_header_key with the rest of the
# shared-doc path.
# A section header line in the legacy shared doc, keyed by a GitHub issue number
# or a Linear ID:
#   "#12345" / "# 12345"          -> GitHub issue number. The leading "#" is
#                                    REQUIRED: bare numbers on their own line in
#                                    a section body (external IDs, dates, counts)
#                                    are not headers, and matching them would
#                                    silently truncate the section.
#   "OBT-36184" / "#OBT-36184"    -> Linear ID. The "#" is optional and a space
#     / "# OBT-36184"                may follow it (the doc uses all three).
# The trailing "(?=\s|$)" requires the identifier to be a whole token, and
# anchoring to the start lets a header carry trailing identifiers/text — e.g.
# "#OBT-36212 and #88494" (only the leading key is used) — while rejecting
# inline references like "see #12345". These shapes were validated against the
# real go/github-pii doc.
#
# The Linear-ID grammar ("[A-Z]+-\d+") is the source-of-truth grammar
# LinearIssue.issue_regex() (recidiviz/issue_tracking/linear/linear_issue.py).
# It is duplicated (not imported) because this module ships standalone in the
# Cloud Build container and is mirrored by the dependency-free skill script, so
# it must not import recidiviz. A test asserts the two stay in agreement.
_TICKET_HEADER_RE = re.compile(
    r"^\s*(?:"
    r"#\s*(?P<linear_hash>[A-Z]+-\d+)"  # "#OBT-…" or "# OBT-…"
    r"|(?P<linear_bare>[A-Z]+-\d+)"  # bare "OBT-…" (unambiguous)
    r"|#\s*(?P<github>\d+)"  # "#<digits>" or "# <digits>"
    r")(?=\s|$)"
)


def extract_pii_doc_id(issue_body: str) -> str | None:
    """Returns the ID of the ticket's private PII doc, or None if none is linked.

    Tickets filed before the per-ticket cutover have no doc banner, so a None
    here means the caller should fall back to the shared go/github-pii doc.
    """
    match = _PII_DOC_LINK_RE.search(issue_body)
    return match.group(1) if match else None


def _ticket_header_key(line: str) -> str | None:
    """Return the normalized ticket key (GitHub issue number or Linear ID) if
    `line` is a section header, otherwise None."""
    match = _TICKET_HEADER_RE.match(line)
    if match is None:
        return None
    # Exactly one alternative matches, so exactly one group is non-None.
    return next(group for group in match.groups() if group is not None)


def _append_content(content: list[dict], lines: list[str], current_line: str) -> str:
    """Flatten Docs API structural elements into `lines`.

    Returns the unterminated tail — a paragraph's text ends with "\\n", so text
    left over after the last newline carries into the next element.
    """
    for elem in content:
        if "paragraph" in elem:
            for run in elem["paragraph"].get("elements", []):
                if "textRun" in run:
                    current_line += run["textRun"]["content"]
                elif "inlineObjectElement" in run:
                    current_line += IMAGE_PLACEHOLDER
            parts = current_line.split("\n")
            lines.extend(parts[:-1])
            current_line = parts[-1]
        elif "table" in elem:
            for row in elem["table"].get("tableRows", []):
                for cell in row.get("tableCells", []):
                    current_line = _append_content(
                        cell.get("content", []), lines, current_line
                    )
    return current_line


def parse_doc(doc: dict) -> list[str]:
    """Parse a Docs API JSON response into text lines with [IMAGE] placeholders."""
    lines: list[str] = []
    trailing = _append_content(doc.get("body", {}).get("content", []), lines, "")
    if trailing:
        lines.append(trailing)
    return lines


def find_issue_section(lines: list[str], identifiers: list[str]) -> list[str]:
    """Return the go/github-pii section for any of the given ticket identifiers.

    TODO(OBT-44025): remove — only the legacy shared-doc path calls this.

    `identifiers` may contain a GitHub issue number (e.g. "12345") and/or a
    Linear identifier (e.g. "OBT-36184"). In the doc, each ticket's PII entry
    starts with a header line (either flavor) and runs until the next such
    header. Returns the first matching section, or an empty list if none match.

    An entry may stack its identifiers on consecutive lines — "#95175" then
    "OBT-42969" for the same ticket — so a following header line is absorbed into
    this section when its key is also one of `identifiers`. Only then: a header
    for some *other* ticket ends the section, because swallowing it would return
    a different client's PII.
    """
    wanted = {i for i in identifiers if i and i.strip()}
    output: list[str] = []
    for i, line in enumerate(lines):
        if _ticket_header_key(line) in wanted:
            output.append(line)
            j = i + 1
            while j < len(lines) and _ticket_header_key(lines[j]) in wanted:
                output.append(lines[j])
                j += 1
            for k in range(j, len(lines)):
                if _ticket_header_key(lines[k]) is not None:
                    break
                output.append(lines[k])
            break
    return output


def section_has_content(section_lines: list[str]) -> bool:
    """Returns True if a shared-doc section has anything beyond its header line.

    A section that is only a header carries no PII, so callers must treat it as
    a miss rather than passing the bare header on to the agent.

    TODO(OBT-44025): remove — only the legacy shared-doc path calls this.
    """
    return any(line.strip() for line in section_lines[1:])
