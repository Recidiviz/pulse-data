"""The issues and blocking relations that a Linear project's dependency graph
draws, shaped from raw Linear API responses and stored as YAML."""
import datetime
import re
from pathlib import Path
from typing import Any

import attr
import yaml

from recidiviz.common import attr_validators
from recidiviz.issue_tracking.linear.linear_types import LinearStateType
from recidiviz.tools.linear.issue_dependency_graph.project_display_config import (
    ProjectDisplayConfig,
)
from recidiviz.utils.types import assert_type
from recidiviz.utils.yaml_dict import YAMLDict

# Status keys the rendered page colors nodes by. These are narrower than Linear's
# workflow state types: `started` splits into `review` and `progress`, because the
# page offers a "Treat In Review as Done" toggle.
STATUS_TRIAGE = "triage"
STATUS_BACKLOG = "backlog"
STATUS_UNSTARTED = "todo"
STATUS_IN_PROGRESS = "progress"
STATUS_IN_REVIEW = "review"
STATUS_DONE = "done"

# The Linear relation type that means "the source issue blocks the related issue".
_BLOCKS_RELATION_TYPE = "blocks"

# A `blocks` edge, as stored in the YAML: "<blocker> -> <blocked>".
_EDGE_SEPARATOR = " -> "

_YAML_NOTE = (
    "Generated by recidiviz.tools.linear.generate_issue_dependency_graph_html. "
    "Re-run that script to refresh from Linear. Hand-edits are allowed, and can be "
    "re-rendered without a Linear call by passing --from-yaml."
)


def _status_for_state(state: dict) -> str:
    """Returns the graph status key for a Linear workflow state.

    Linear's `started` type covers both in-progress and in-review work, so this
    splits it on whether the state's name mentions review.
    """
    state_type = LinearStateType(state["type"])
    if state_type is LinearStateType.COMPLETED:
        return STATUS_DONE
    if state_type is LinearStateType.TRIAGE:
        return STATUS_TRIAGE
    if state_type is LinearStateType.BACKLOG:
        return STATUS_BACKLOG
    if state_type is LinearStateType.UNSTARTED:
        return STATUS_UNSTARTED
    if state_type is LinearStateType.STARTED:
        return (
            STATUS_IN_REVIEW
            if "review" in state["name"].lower()
            else STATUS_IN_PROGRESS
        )
    raise ValueError(
        f"Unexpected Linear state type [{state_type}] for state [{state['name']}]"
    )


def _display_title(title: str) -> str:
    """Returns the title with up to two leading `[...]` tags removed.

    Issue titles carry tags that the graph does not need to repeat, e.g.
    `[CNI][Extractor Config] Parse the collection config` becomes
    `Parse the collection config`. A graph node is too narrow for the full title.
    """
    return re.sub(r"^(\[[^\]]*\]\s*){1,2}", "", title).strip()


def _issue_sort_key(issue_id: str) -> tuple[str, int]:
    """Returns a stable sort key for a Linear issue identifier like `OBT-31981`.

    Sorts on the team key, then on the number as a number. A plain string sort
    would order `OBT-3`, `OBT-31`, `OBT-4`.
    """
    team_key, _, number = issue_id.rpartition("-")
    return team_key, int(number)


@attr.define(frozen=True, kw_only=True)
class GraphMilestone:
    """One project milestone the graph draws a box for."""

    milestone_id: str = attr.ib(validator=attr_validators.is_non_empty_str)
    """The milestone's UUID in Linear."""

    name: str = attr.ib(validator=attr_validators.is_non_empty_str)
    """The milestone's full name, shown on its box."""

    short_name: str = attr.ib(validator=attr_validators.is_non_empty_str)
    """The abbreviation from the project display config, shown on each issue."""

    sort_order: float = attr.ib(validator=attr_validators.is_float)
    """Linear's own ordering value for the milestone. Boxes run left to right in
    ascending `sort_order`, so the graph matches the order Linear displays.
    """

    def to_dict(self) -> dict[str, Any]:
        return {
            "short_name": self.short_name,
            "name": self.name,
            "milestone_id": self.milestone_id,
            "sort_order": float(self.sort_order),
        }

    @classmethod
    def from_yaml_dict(cls, yaml_dict: YAMLDict) -> "GraphMilestone":
        milestone = GraphMilestone(
            short_name=yaml_dict.pop("short_name", str),
            name=yaml_dict.pop("name", str),
            milestone_id=yaml_dict.pop("milestone_id", str),
            sort_order=yaml_dict.pop("sort_order", float),
        )
        if yaml_dict:
            raise ValueError(
                f"Found unexpected values for milestone [{milestone.name}]: "
                f"{repr(yaml_dict.get())}"
            )
        return milestone


@attr.define(frozen=True, kw_only=True)
class GraphIssue:
    """One issue the graph draws a node for."""

    issue_id: str = attr.ib(validator=attr_validators.is_non_empty_str)
    """The issue's human-readable Linear identifier, e.g. `OBT-31981`."""

    milestone_short_name: str = attr.ib(validator=attr_validators.is_non_empty_str)
    """The `short_name` of the milestone whose box holds this issue."""

    status: str = attr.ib(validator=attr_validators.is_non_empty_str)
    """The graph status key, one of the `STATUS_*` constants above."""

    assignee: str | None = attr.ib(validator=attr_validators.is_opt_str)
    """The assignee's display name, or None when the issue is unassigned."""

    labels: list[str] = attr.ib(validator=attr_validators.is_list_of_non_empty_str)
    """Every Linear label on the issue, sorted. The page's "Labels to exclude"
    dropdown hides an issue when any of these labels is checked.
    """

    title: str = attr.ib(validator=attr_validators.is_non_empty_str)
    """The issue title, with its leading `[...]` tags removed."""

    def to_dict(self) -> dict[str, Any]:
        return {
            "issue_id": self.issue_id,
            "milestone_short_name": self.milestone_short_name,
            "status": self.status,
            "assignee": self.assignee,
            "labels": self.labels,
            "title": self.title,
        }

    @classmethod
    def from_yaml_dict(cls, yaml_dict: YAMLDict) -> "GraphIssue":
        issue = GraphIssue(
            issue_id=yaml_dict.pop("issue_id", str),
            milestone_short_name=yaml_dict.pop("milestone_short_name", str),
            status=yaml_dict.pop("status", str),
            assignee=yaml_dict.pop_optional("assignee", str),
            labels=yaml_dict.pop_list_optional("labels", str) or [],
            title=yaml_dict.pop("title", str),
        )
        if yaml_dict:
            raise ValueError(
                f"Found unexpected values for issue [{issue.issue_id}]: "
                f"{repr(yaml_dict.get())}"
            )
        return issue


@attr.define(frozen=True, kw_only=True)
class IssueDependencyGraph:
    """Everything the rendered page draws: the milestone boxes, the issues inside
    them, and the blocking relations between those issues."""

    project_name: str = attr.ib(validator=attr_validators.is_non_empty_str)
    """The Linear project the graph was built from."""

    generated_at: str = attr.ib(validator=attr_validators.is_non_empty_str)
    """The UTC timestamp of the Linear fetch, in ISO-8601 form."""

    milestones: list[GraphMilestone] = attr.ib(
        validator=[
            attr_validators.is_non_empty_list,
            attr_validators.is_list_of(GraphMilestone),
        ]
    )
    """The milestone boxes, in ascending `sort_order`."""

    issues: list[GraphIssue] = attr.ib(validator=attr_validators.is_list_of(GraphIssue))
    """The graph's issues, sorted by team key and then by issue number."""

    edges: list[tuple[str, str]] = attr.ib(
        validator=attr_validators.is_list_where_each(attr.validators.instance_of(tuple))
    )
    """Blocking relations as `(blocker_id, blocked_id)` pairs. Both endpoints are
    always issues in `issues`.
    """

    labels_excluded_by_default: list[str] = attr.ib(
        validator=attr_validators.is_list_of_non_empty_str
    )
    """The config's default-hidden labels, carried through so a re-render from YAML
    starts the page in the same state as the original fetch.
    """

    @property
    def all_labels(self) -> list[str]:
        """Returns every distinct label found on any issue in the graph, sorted.

        This is the full checkbox list for the page's "Labels to exclude" dropdown,
        so a reader can hide a label the config says nothing about.
        """
        return sorted({label for issue in self.issues for label in issue.labels})

    def __attrs_post_init__(self) -> None:
        short_names = {milestone.short_name for milestone in self.milestones}
        unknown_short_names = {
            issue.milestone_short_name
            for issue in self.issues
            if issue.milestone_short_name not in short_names
        }
        if unknown_short_names:
            raise ValueError(
                f"Found issues in milestones missing from the graph: "
                f"{sorted(unknown_short_names)}."
            )
        issue_ids = {issue.issue_id for issue in self.issues}
        dangling = {
            issue_id
            for edge in self.edges
            for issue_id in edge
            if issue_id not in issue_ids
        }
        if dangling:
            raise ValueError(
                f"Found edge endpoints that are not issues in the graph: "
                f"{sorted(dangling)}."
            )

    def to_dict(self) -> dict[str, Any]:
        """Returns the graph as the plain structure written to the YAML file."""
        return {
            "project_name": self.project_name,
            "generated_at": self.generated_at,
            "note": _YAML_NOTE,
            "milestones": [milestone.to_dict() for milestone in self.milestones],
            "all_labels": self.all_labels,
            "labels_excluded_by_default": self.labels_excluded_by_default,
            "issues": [issue.to_dict() for issue in self.issues],
            "edges": [
                f"{blocker}{_EDGE_SEPARATOR}{blocked}"
                for blocker, blocked in self.edges
            ],
        }

    def write_yaml(self, yaml_path: str | Path) -> None:
        """Writes the graph to |yaml_path| as YAML."""
        with open(yaml_path, "w", encoding="utf-8") as f:
            yaml.safe_dump(
                self.to_dict(), f, sort_keys=False, allow_unicode=True, width=200
            )

    @classmethod
    def from_yaml(cls, yaml_path: str | Path) -> "IssueDependencyGraph":
        """Returns the graph parsed from the YAML file at |yaml_path|."""
        file_contents = YAMLDict.from_path(str(yaml_path))
        project_name = file_contents.pop("project_name", str)
        generated_at = file_contents.pop("generated_at", str)
        # `note` is a human-facing reminder written by to_dict; pop it so the
        # unused-key check below still holds.
        file_contents.pop("note", str)
        milestones = [
            GraphMilestone.from_yaml_dict(milestone_dict)
            for milestone_dict in file_contents.pop_dicts("milestones")
        ]
        # `all_labels` is derived from the issues; pop and discard it.
        file_contents.pop_list_optional("all_labels", str)
        labels_excluded_by_default = (
            file_contents.pop_list_optional("labels_excluded_by_default", str) or []
        )
        issues = [
            GraphIssue.from_yaml_dict(issue_dict)
            for issue_dict in file_contents.pop_dicts("issues")
        ]
        edges = [
            _parse_edge(edge)
            for edge in file_contents.pop_list_optional("edges", str) or []
        ]
        if file_contents:
            raise ValueError(
                f"Found unexpected values in [{yaml_path}]: {repr(file_contents.get())}"
            )
        return IssueDependencyGraph(
            project_name=project_name,
            generated_at=generated_at,
            milestones=milestones,
            issues=issues,
            edges=edges,
            labels_excluded_by_default=labels_excluded_by_default,
        )


def _parse_edge(edge: str) -> tuple[str, str]:
    """Returns the `(blocker, blocked)` pair encoded in a `"<a> -> <b>"` string."""
    blocker, separator, blocked = edge.partition(_EDGE_SEPARATOR)
    if not separator or not blocker.strip() or not blocked.strip():
        raise ValueError(
            f"Could not parse edge [{edge}]; expected the form "
            f"[<blocker>{_EDGE_SEPARATOR}<blocked>]."
        )
    return blocker.strip(), blocked.strip()


def build_graph(
    *,
    config: ProjectDisplayConfig,
    milestones: list[GraphMilestone],
    issue_nodes_by_milestone_id: dict[str, list[dict]],
    generated_at: datetime.datetime,
) -> IssueDependencyGraph:
    """Returns the dependency graph for the raw Linear issue nodes of each milestone.

    Drops canceled issues always, and drops issues with sub-issues when the config
    sets `exclude_parent_issues`. Keeps a blocking relation only when both of its
    endpoints survive those filters, including a relation that crosses milestones.
    """
    milestone_short_name_by_id = {
        milestone.milestone_id: milestone.short_name for milestone in milestones
    }

    def is_in_scope(node: dict) -> bool:
        if LinearStateType(node["state"]["type"]) is LinearStateType.CANCELED:
            return False
        if config.exclude_parent_issues and node["children"]["nodes"]:
            return False
        return True

    issues: list[GraphIssue] = []
    all_nodes: list[dict] = []
    for milestone_id, nodes in issue_nodes_by_milestone_id.items():
        short_name = milestone_short_name_by_id[milestone_id]
        all_nodes.extend(nodes)
        for node in nodes:
            if not is_in_scope(node):
                continue
            assignee = node["assignee"]
            issues.append(
                GraphIssue(
                    issue_id=node["identifier"],
                    milestone_short_name=short_name,
                    status=_status_for_state(node["state"]),
                    assignee=assignee["name"] if assignee else None,
                    labels=sorted(label["name"] for label in node["labels"]["nodes"]),
                    title=_display_title(node["title"]),
                )
            )
    issues.sort(key=lambda issue: _issue_sort_key(issue.issue_id))

    kept_issue_ids = {issue.issue_id for issue in issues}
    edges: set[tuple[str, str]] = set()
    for node in all_nodes:
        for relation in node["relations"]["nodes"]:
            if relation["type"] != _BLOCKS_RELATION_TYPE:
                continue
            blocker = relation["issue"]["identifier"]
            blocked = relation["relatedIssue"]["identifier"]
            if blocker in kept_issue_ids and blocked in kept_issue_ids:
                edges.add((blocker, blocked))

    return IssueDependencyGraph(
        project_name=config.project_name,
        generated_at=generated_at.replace(microsecond=0).isoformat(),
        milestones=milestones,
        issues=issues,
        edges=sorted(
            edges,
            key=lambda edge: (_issue_sort_key(edge[0]), _issue_sort_key(edge[1])),
        ),
        labels_excluded_by_default=config.labels_excluded_by_default,
    )


def graph_milestones_for_config(
    *, config: ProjectDisplayConfig, linear_milestone_nodes: list[dict]
) -> list[GraphMilestone]:
    """Returns a GraphMilestone for each milestone the config includes, in ascending
    `sortOrder`.

    Raises if the config names a milestone the project does not have, since a typo
    would otherwise silently drop that milestone's issues from the graph.
    """
    node_by_name = {node["name"]: node for node in linear_milestone_nodes}
    missing_names = [
        milestone.name
        for milestone in config.milestones
        if milestone.name not in node_by_name
    ]
    if missing_names:
        raise ValueError(
            f"Project display config for [{config.project_name}] names milestones "
            f"that the project does not have: {sorted(missing_names)}. Project "
            f"milestones are: {sorted(node_by_name)}."
        )
    graph_milestones = [
        GraphMilestone(
            milestone_id=assert_type(node_by_name[milestone.name]["id"], str),
            name=milestone.name,
            short_name=milestone.short_name,
            sort_order=float(node_by_name[milestone.name]["sortOrder"]),
        )
        for milestone in config.milestones
    ]
    return sorted(graph_milestones, key=lambda milestone: milestone.sort_order)
