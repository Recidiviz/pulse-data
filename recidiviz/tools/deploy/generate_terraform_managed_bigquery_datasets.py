"""Generates terraform_managed_bigquery_datasets.yaml, the registry of BigQuery
datasets whose dataset shells are created by Terraform. The registry is consumed
by recidiviz/tools/deploy/terraform/bigquery-datasets.tf, which creates each
registered dataset at deploy time.

Registered datasets come from two kinds of sources:
  - datasets declared directly in this module (_NON_SOURCE_TABLE_TERRAFORM_MANAGED_DATASETS);
  - datasets generated by the source-table collections: every dataset whose
    tables the source-table framework manages
    (update_config.attempt_to_manage=True) is registered, so it exists before
    the first pipeline or service touches it. The framework's own dataset
    creation is a get-or-create, so it no-ops on these Terraform-created
    datasets and still covers sandbox datasets, which are intentionally not
    registered.

GenerateTerraformManagedBigqueryDatasetsTest fails if the checked-in YAML is
stale. Regenerate it with:
    uv run python -m recidiviz.tools.deploy.generate_terraform_managed_bigquery_datasets
"""
import os
from collections import defaultdict

import attr
import more_itertools

from recidiviz.calculator.query.experiments_metadata.dataset_config import (
    EXPERIMENTS_METADATA_DATASET,
)
from recidiviz.common import attr_validators
from recidiviz.source_tables.collect_all_source_table_configs import (
    build_source_table_repository_for_collected_schemata,
    get_source_table_datasets_to_descriptions,
)
from recidiviz.source_tables.externally_managed.datasets import (
    EXTERNALLY_MANAGED_DATASETS_TO_DESCRIPTIONS,
    MANUALLY_UPDATED_SOURCE_TABLES_DATASET,
)
from recidiviz.source_tables.source_table_repository import SourceTableRepository
from recidiviz.tools import deploy
from recidiviz.tools.ingest.operations.constants import RAW_DATA_DIFF_RESULTS_DATASET_ID
from recidiviz.utils.environment import DATA_PLATFORM_GCP_PROJECTS
from recidiviz.utils.metadata import local_project_id_override
from recidiviz.utils.yaml import prettier_friendly_yaml_dump

TERRAFORM_MANAGED_BIGQUERY_DATASETS_YAML_PATH = os.path.join(
    os.path.dirname(deploy.__file__),
    "terraform",
    "config",
    "terraform_managed_bigquery_datasets.yaml",
)

_SEVEN_DAYS_MS = 7 * 24 * 60 * 60 * 1000

# The value of each registry entry, as dumped to YAML.
RegistryEntry = dict[str, str | int | list[str]]


@attr.define(frozen=True, kw_only=True)
class TerraformManagedDataset:
    """A BigQuery dataset whose shell and dataset-level IAM grants are created
    and managed by Terraform.
    """

    description: str = attr.ib(validator=attr_validators.is_non_empty_str)
    """The BigQuery dataset description."""

    default_table_expiration_ms: int | None = attr.ib(
        default=None, validator=attr_validators.is_opt_positive_int
    )
    """Default expiration applied to tables in the dataset, if any."""


# Terraform-managed datasets that are not registered in the source-table
# repository: Terraform creates the dataset shell, and whatever writes the
# tables inside is not the source-table framework (one-off scripts, admin-panel
# logging, etc.), so each dataset carries a hand-written description here.
# GenerateTerraformManagedBigqueryDatasetsTest enforces that these datasets stay
# out of the source-table repository.
_NON_SOURCE_TABLE_TERRAFORM_MANAGED_DATASETS: dict[str, TerraformManagedDataset] = {
    EXPERIMENTS_METADATA_DATASET: TerraformManagedDataset(
        description="This dataset contains the metadata for our experiments.",
    ),
    # TODO(OBT-45863): Remove once experiment_assignments_large migrates out of
    # manually_updated_source_tables and this dataset leaves the source-table
    # repository. Until then it is the one entry here that is also registered in
    # the repository (as externally_managed), so its description comes from that
    # collection rather than drifting from it.
    MANUALLY_UPDATED_SOURCE_TABLES_DATASET: TerraformManagedDataset(
        description=EXTERNALLY_MANAGED_DATASETS_TO_DESCRIPTIONS[
            MANUALLY_UPDATED_SOURCE_TABLES_DATASET
        ],
    ),
    RAW_DATA_DIFF_RESULTS_DATASET_ID: TerraformManagedDataset(
        description=(
            "This dataset contains tables that store the output of raw data "
            "comparisons generated by compare_raw_data.py."
        ),
        default_table_expiration_ms=_SEVEN_DAYS_MS,
    ),
    "user_mgmt_logs": TerraformManagedDataset(
        description=(
            "This dataset contains logs of user actions from the "
            "user/permissions management admin panel pages."
        ),
    ),
}


def _source_table_datasets(
    repository: SourceTableRepository,
    *,
    dataset_descriptions: dict[str, str],
) -> dict[str, TerraformManagedDataset]:
    """Returns a TerraformManagedDataset for every dataset generated by the
    source-table collections whose tables the source-table framework manages.

    Args:
        repository: The repository of all source table collections.
        dataset_descriptions: The description of every source-table dataset, as
            returned by get_source_table_datasets_to_descriptions, which raises
            if any two collections sharing a dataset disagree on it.
    """
    collections_by_dataset = defaultdict(list)
    for collection in repository.source_table_collections:
        if collection.update_config.attempt_to_manage:
            collections_by_dataset[collection.dataset_id].append(collection)

    datasets: dict[str, TerraformManagedDataset] = {}
    for dataset_id, collections in collections_by_dataset.items():
        expirations = {c.default_table_expiration_ms for c in collections}
        if len(expirations) != 1:
            raise ValueError(
                f"Expected all source table collections in dataset "
                f"[{dataset_id}] to declare the same "
                f"default_table_expiration_ms; found: [{expirations}]"
            )
        datasets[dataset_id] = TerraformManagedDataset(
            description=dataset_descriptions[dataset_id],
            default_table_expiration_ms=expirations.pop(),
        )
    return datasets


def _terraform_managed_datasets(
    project_id: str,
) -> dict[str, TerraformManagedDataset]:
    """Returns every Terraform-managed dataset for the given project, by
    dataset id, merged from all sources."""
    with local_project_id_override(project_id):
        repository = build_source_table_repository_for_collected_schemata(
            project_id=project_id
        )
        # Raises if any two collections sharing a dataset disagree on its
        # description, so the description Terraform writes cannot drift from
        # the ones the collections assert.
        dataset_descriptions = get_source_table_datasets_to_descriptions(project_id)

    datasets = dict(_NON_SOURCE_TABLE_TERRAFORM_MANAGED_DATASETS)
    for dataset_id, dataset in datasets.items():
        if (
            dataset_id in dataset_descriptions
            and dataset_descriptions[dataset_id] != dataset.description
        ):
            raise ValueError(
                f"Dataset [{dataset_id}] is declared in "
                f"_NON_SOURCE_TABLE_TERRAFORM_MANAGED_DATASETS with description "
                f"[{dataset.description}], but its source table collections "
                f"declare [{dataset_descriptions[dataset_id]}]. Update one to "
                f"match the other."
            )
    for dataset_id, dataset in _source_table_datasets(
        repository, dataset_descriptions=dataset_descriptions
    ).items():
        if dataset_id in datasets:
            raise ValueError(
                f"Dataset [{dataset_id}] is declared in "
                f"_NON_SOURCE_TABLE_TERRAFORM_MANAGED_DATASETS but is also generated by the "
                f"source-table collections; remove the explicit declaration."
            )
        datasets[dataset_id] = dataset
    return datasets


def _to_registry_entry(
    dataset: TerraformManagedDataset, *, projects: list[str] | None
) -> RegistryEntry:
    """Returns the YAML registry entry for the given dataset.

    Args:
        dataset: The dataset to serialize.
        projects: The projects the dataset exists in, or None if it exists in
            every data-platform project.
    """
    entry: RegistryEntry = {"description": dataset.description}
    if dataset.default_table_expiration_ms is not None:
        entry["default_table_expiration_ms"] = dataset.default_table_expiration_ms
    if projects is not None:
        entry["projects"] = projects
    return entry


_GENERATED_FILE_HEADER = """\
# AUTOGENERATED FILE -- do not edit by hand.
#
# Generated by recidiviz/tools/deploy/generate_terraform_managed_bigquery_datasets.py,
# which documents the registry format. Consumed by
# recidiviz/tools/deploy/terraform/bigquery-datasets.tf. Regenerate with:
#   uv run python -m recidiviz.tools.deploy.generate_terraform_managed_bigquery_datasets
"""


def build_registry_contents() -> str:
    """Returns the full contents of terraform_managed_bigquery_datasets.yaml."""
    datasets_by_project = {
        project_id: _terraform_managed_datasets(project_id)
        for project_id in DATA_PLATFORM_GCP_PROJECTS
    }

    all_dataset_ids = sorted(
        set().union(*(set(datasets) for datasets in datasets_by_project.values()))
    )
    merged_entries: dict[str, RegistryEntry] = {}
    for dataset_id in all_dataset_ids:
        datasets = {
            project_id: project_datasets[dataset_id]
            for project_id, project_datasets in datasets_by_project.items()
            if dataset_id in project_datasets
        }
        first_dataset = more_itertools.first(datasets.values())
        if any(dataset != first_dataset for dataset in datasets.values()):
            raise ValueError(
                f"Expected dataset [{dataset_id}] to have the same config in "
                f"every project it exists in; found: [{datasets}]"
            )
        merged_entries[dataset_id] = _to_registry_entry(
            first_dataset,
            projects=(
                sorted(datasets)
                if set(datasets) != set(DATA_PLATFORM_GCP_PROJECTS)
                else None
            ),
        )

    return _GENERATED_FILE_HEADER + prettier_friendly_yaml_dump(
        {"datasets": merged_entries}
    )


def main() -> None:
    """Writes the registry to TERRAFORM_MANAGED_BIGQUERY_DATASETS_YAML_PATH."""
    with open(
        TERRAFORM_MANAGED_BIGQUERY_DATASETS_YAML_PATH, "w", encoding="utf-8"
    ) as yaml_file:
        yaml_file.write(build_registry_contents())


if __name__ == "__main__":
    main()
